"""End-to-end: KiCad-8-style Gerber X2/X3 + Excellon vs a FreeCAD-style DXF.

The ECAD and MCAD files are generated by :mod:`tests.cad_fixtures` in exactly the
formats those tools write (KiCad: X2 attributes, ``#@!`` Excellon comments,
Edge_Cuts profile with arcs; FreeCAD: R2000 DXF with exploded LINE/ARC outline,
CIRCLE holes, LWPOLYLINE bodies with elevation/thickness). Neither KiCad nor
FreeCAD is required to run the tests.
"""

from __future__ import annotations

import io
import json
import math
from pathlib import Path

import pytest
import yaml

from pcbsim.cli import EXIT_MECH_NG, EXIT_OK, EXIT_VIOLATIONS, main
from pcbsim.io import load_config
from pcbsim.registration.layermap import load_layer_map
from pcbsim.registration.pipeline import MatchResult, run_match
from pcbsim.registration.transform import Similarity2D
from tests.cad_fixtures import Defects, drawing_transform, write_project

EXAMPLE = Path(__file__).resolve().parents[1] / "examples" / "soc_4layer.yaml"
TOL = 1e-9  # m == 1e-6 mm


def _match(tmp_path: Path, **kw: object) -> tuple[MatchResult, Path, Path, Path]:
    ecad, dxf, lmap = write_project(tmp_path, **kw)
    m = run_match(ecad, [], [dxf], load_layer_map(lmap))
    return m, ecad, dxf, lmap


def _expected(t_board_to_drawing: Similarity2D, unit_scale: float = 1.0) -> Similarity2D:
    """Drawing (read in metres) → board (metres)."""
    t = t_board_to_drawing
    mm = Similarity2D(t.angle, t.tx * 1e-3, t.ty * 1e-3, t.scale, t.mirror)
    inv = mm.inverse()
    return Similarity2D(inv.angle, inv.tx, inv.ty, inv.scale * unit_scale, inv.mirror)


def _ng(m: MatchResult, cat: str) -> list[str]:
    return [i.subject for i in m.report.items if i.category == cat and i.status.value == "NG"]


def test_clean_project_passes(tmp_path: Path) -> None:
    m, *_ = _match(tmp_path)
    assert m.ok, [i.to_dict() for i in m.report.ng()]
    r = m.registration
    assert len(r.matches) == 5
    assert r.transform.distance_to(_expected(drawing_transform()), 0.05) < TOL
    assert m.ecad.component_source == "gerber_x3"
    assert {b.ref for b in m.bodies if b.role == "comp_3d"} == {"U1", "U2", "L1", "U3"}
    names = {b.name for b in m.boundaries}
    assert names == {"hs_U1", "chassis_CHASSIS_BL", "chassis_CHASSIS_TR", "case_CASE_LID"}


def test_bottom_view_mirror_and_inch_units(tmp_path: Path) -> None:
    t = drawing_transform(rot_deg=-117.0, mirror=True)
    m, *_ = _match(tmp_path, t=t, unit="in", insunits=4)  # inch geometry mislabelled as mm
    r = m.registration
    assert r.transform.mirror
    assert r.transform.scale == pytest.approx(25.4)
    assert r.unit_warning is not None
    assert "inch" in r.unit_warning
    assert r.transform.distance_to(_expected(t, 25.4), 0.05) < TOL
    assert not _ng(m, "hole_position")
    assert not _ng(m, "component_position")


def test_inch_drawing_with_correct_header(tmp_path: Path) -> None:
    t = drawing_transform(rot_deg=200.0)
    m, *_ = _match(tmp_path, t=t, unit="in")
    assert m.ok
    assert m.registration.transform.scale == pytest.approx(1.0)
    assert m.registration.transform.distance_to(_expected(t), 0.05) < TOL


def test_injected_hole_defects(tmp_path: Path) -> None:
    d = Defects(hole_shift={1: (0.25, 0.0)}, hole_diameter={2: 3.5}, extra_hole=(30.0, 10.0, 3.0))
    m, *_ = _match(tmp_path, defects=d)
    assert _ng(m, "hole_position") == ["hole @(56.50, 3.50) ⌀3.20"]
    assert _ng(m, "hole_diameter") == ["hole @(56.50, 36.50) ⌀3.20"]
    assert len(_ng(m, "hole_extra")) == 1
    assert not m.ok


def test_missing_hole_and_cutout(tmp_path: Path) -> None:
    m, *_ = _match(tmp_path, defects=Defects(drop_hole=0, no_cutout=True))
    assert len(_ng(m, "hole_missing")) == 1
    assert len(_ng(m, "cutout")) == 1


def test_injected_component_defects(tmp_path: Path) -> None:
    d = Defects(part_shift={"U2": (0.0, 1.2)}, part_rot={"L1": 5.0})
    m, *_ = _match(tmp_path, defects=d)
    assert _ng(m, "component_position") == ["U2"]
    assert _ng(m, "component_rotation") == ["L1"]


def test_injected_height_violation(tmp_path: Path) -> None:
    m, *_ = _match(tmp_path, defects=Defects(heatsink_height=12.8))
    (subject,) = _ng(m, "height")
    assert subject == "heatsink HS_U1"
    keep = next(i for i in m.report.items if i.subject == "U3")
    assert keep.status.value == "OK"
    assert "ceiling 2.00 mm" in keep.message


def test_cli_match_writes_reports(tmp_path: Path) -> None:
    ecad, dxf, lmap = write_project(tmp_path)
    html = tmp_path / "out" / "match.html"
    buf = io.StringIO()
    code = main(
        [
            "match", "--gerber", str(ecad), "--drill", str(ecad / "board-NPTH.drl"),
            "--drill", str(ecad / "board-PTH.drl"), "--mech", str(dxf), "--map", str(lmap),
            "--report", str(html),
        ],
        out=buf,
    )  # fmt: skip
    assert code == EXIT_OK, buf.getvalue()
    text = html.read_text()
    assert "<svg" in text
    assert "PASS" in text
    doc = json.loads(html.with_suffix(".json").read_text())
    assert doc["kind"] == "pcbsim.match"
    assert doc["ok"] is True
    assert doc["registration"]["matched"] == 5
    assert math.isclose(doc["registration"]["transform"]["rotation_deg"], -30.0, abs_tol=1e-9)


def test_cli_match_ng_exit_code_and_table(tmp_path: Path) -> None:
    ecad, dxf, lmap = write_project(tmp_path, defects=Defects(hole_shift={0: (0.3, 0.0)}))
    buf = io.StringIO()
    html = tmp_path / "r.html"
    args = ["match", "--gerber", str(ecad), "--mech", str(dxf), "--map", str(lmap)]
    assert main([*args, "--report", str(html)], out=buf) == EXIT_VIOLATIONS
    assert "hole_position" in buf.getvalue()
    assert "NG items" in html.read_text()


def _sim_config(tmp_path: Path, match_json: Path) -> Path:
    cfg = yaml.safe_load(EXAMPLE.read_text())
    cfg["thermal_boundaries"] = []
    cfg["analysis"]["solvers"] = ["thermal"]
    cfg["analysis"]["mesh"] = {"cell": 2.0}
    cfg["analysis"]["options"] = {"thermal": {"ambient": 25}}
    cfg["mechanical"] = {"match": str(match_json)}
    p = tmp_path / "sim.yaml"
    p.write_text(yaml.safe_dump(cfg))
    return p


def test_run_applies_match_boundaries(tmp_path: Path) -> None:
    ecad, dxf, lmap = write_project(tmp_path / "proj")
    mj = tmp_path / "match.json"
    assert main(["match", "--gerber", str(ecad), "--mech", str(dxf), "--map", str(lmap),
                 "--json", str(mj)], out=io.StringIO()) == EXIT_OK  # fmt: skip
    cfg = load_config(_sim_config(tmp_path, mj))
    assert cfg.mechanical is not None
    assert cfg.mechanical.ok
    tb = {t.name: t for t in cfg.board.thermal_boundaries}
    assert tb["hs_U1"].component == "U1"
    assert tb["hs_U1"].resistance == pytest.approx(6.0)
    assert tb["chassis_CHASSIS_BL"].temperature == pytest.approx(318.15)
    buf = io.StringIO()
    code = main(["run", str(_sim_config(tmp_path, mj)), "--no-plots", "--out", str(tmp_path / "r")],
                out=buf)  # fmt: skip
    assert code in (EXIT_OK, EXIT_VIOLATIONS)
    assert "thermal boundaries from MCAD: hs_U1" in buf.getvalue()


def test_run_refuses_ng_match_without_force(tmp_path: Path) -> None:
    ecad, dxf, lmap = write_project(tmp_path / "proj", defects=Defects(heatsink_height=14.0))
    mj = tmp_path / "match.json"
    args = ["match", "--gerber", str(ecad), "--mech", str(dxf), "--map", str(lmap)]
    assert main([*args, "--json", str(mj)], out=io.StringIO()) == EXIT_VIOLATIONS
    cfg = _sim_config(tmp_path, mj)
    out = ["--no-plots", "--out", str(tmp_path / "r")]
    buf = io.StringIO()
    assert main(["run", str(cfg), *out], out=buf) == EXIT_MECH_NG
    assert "NG item" in buf.getvalue()
    buf = io.StringIO()
    assert main(["run", str(cfg), "--force", *out], out=buf) in (EXIT_OK, EXIT_VIOLATIONS)
    assert "--force given" in buf.getvalue()
